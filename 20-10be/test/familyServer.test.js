const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');

test('JSON API: đăng nhập, gửi, chống trùng, bảo vệ hộp thư và dữ liệu còn trên đĩa', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'family-api-'));
  process.env.DATA_DIR = dir;
  process.env.ADMIN_USERNAME = 'admin';
  process.env.ADMIN_PASSWORD = '1';
  process.env.JWT_SECRET = crypto.randomBytes(32).toString('hex');
  const app = require('../server');
  assert.ok(!Object.keys(require.cache).some(file => file.endsWith('/config/db.js')));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); fs.rmSync(dir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = (url, data) => fetch(base + url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) });
  assert.equal((await (await fetch(base + '/api/ready')).json()).storage, 'json');
  assert.equal((await fetch(base + '/api/admin/feedback')).status, 401);
  assert.equal((await post('/api/feedback', { name: 'Mẹ', content: '' })).status, 400);
  const payload = { name: 'Ngọc', sender: 'Hiếu', content: 'Cảm ơn em, chị rất vui! 🌷', requestId: crypto.randomUUID() };
  assert.equal((await post('/api/feedback', payload)).status, 201);
  assert.equal((await post('/api/feedback', payload)).status, 201);
  const rows = JSON.parse(fs.readFileSync(path.join(dir, 'feedback.json'), 'utf8'));
  assert.equal(rows.length, 1);
  assert.equal(rows[0].recipient, 'chị Ngọc');
  assert.equal(rows[0].sender, 'Hiếu');
  assert.match(rows[0].location.label, /nội bộ/);
  assert.equal(rows[0].content, payload.content);
  const login = await (await post('/api/auth/admin/login', { username: 'admin', password: '1' })).json();
  assert.ok(login.data.token);
  const inbox = await (await fetch(base + '/api/admin/feedback', { headers: { Authorization: `Bearer ${login.data.token}` } })).json();
  assert.equal(inbox.data.total, 1);
  assert.equal(inbox.data.items[0].content, payload.content);
  assert.equal(inbox.data.items[0].sender, 'Hiếu');
  assert.match(inbox.data.items[0].location.label, /nội bộ/);
  const authHeaders = { Authorization: `Bearer ${login.data.token}` };
  const publicThread = await (await fetch(base + '/api/feedback?name=ngoc')).json();
  assert.equal(publicThread.data.items[0].recipient, 'chị Ngọc');
  assert.equal(publicThread.data.items[0].content, payload.content);
  assert.equal(publicThread.data.items[0].name, undefined);
  assert.equal(publicThread.data.items[0].sender, 'Hiếu');
  assert.equal(publicThread.data.items[0].location, undefined);
  const upload = new FormData();
  upload.append('name', 'mẹ'); upload.append('content', 'Ảnh của mẹ'); upload.append('requestId', crypto.randomUUID());
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9Zl1sAAAAASUVORK5CYII=', 'base64');
  upload.append('images', new Blob([png, Buffer.alloc(2 * 1024 * 1024)], { type: 'image/png' }), 'family.png');
  const imageResponse = await fetch(base + '/api/feedback', { method: 'POST', body: upload });
  assert.equal(imageResponse.status, 201);
  const motherThread = await (await fetch(base + '/api/feedback?name=Y%E1%BA%BFn')).json();
  const imageUrl = motherThread.data.items[0].images[0];
  assert.ok(imageUrl.startsWith('/uploads/'));
  assert.equal((await fetch(base + '/api/admin/images')).status, 401);
  const gallery = await (await fetch(base + '/api/admin/images', { headers: authHeaders })).json();
  assert.equal(gallery.data.total, 1);
  assert.equal(gallery.data.items[0].url, imageUrl);
  assert.equal(gallery.data.items[0].recipient, 'Mẹ');
  assert.equal(gallery.data.totalBytes, png.length + 2 * 1024 * 1024);
  const imageDownload = await fetch(base + imageUrl);
  assert.equal(imageDownload.status, 200);
  assert.equal((await imageDownload.arrayBuffer()).byteLength, png.length + 2 * 1024 * 1024);
  const deleteImage = await fetch(`${base}/api/admin/images/${gallery.data.items[0].feedbackId}/${gallery.data.items[0].index}`, { method: 'DELETE', headers: authHeaders });
  assert.equal(deleteImage.status, 200);
  assert.equal((await (await fetch(base + '/api/admin/images', { headers: authHeaders })).json()).data.total, 0);
  assert.equal((await (await fetch(base + '/api/feedback?name=Y%E1%BA%BFn')).json()).data.items[0].images.length, 0);
  assert.equal((await fetch(base + imageUrl)).status, 404);
  await post('/api/visits', { sessionId: 'test-session', page: '/' });
  await post('/api/visits', { sessionId: 'test-session', page: '/celebrate/me' });
  const overview = await (await fetch(base + '/api/admin/overview', { headers: authHeaders })).json();
  assert.equal(overview.data.visitCount, 2);
  assert.equal(overview.data.visitors, 1);
  assert.equal(overview.data.feedbackCount, 2);
  assert.match(overview.data.visits[0].location.label, /nội bộ/);
  assert.equal(overview.data.visits[0].ip, '127.0.0.1');
  assert.equal((await fetch(`${base}/api/admin/visits/${overview.data.visits[0].id}`, { method: 'DELETE', headers: authHeaders })).status, 200);
  assert.equal((await (await fetch(base + '/api/admin/overview', { headers: authHeaders })).json()).data.visitCount, 1);
  const custom = await (await fetch(base + '/api/admin/greetings', { method: 'POST', headers: { ...authHeaders, 'Content-Type': 'application/json' }, body: JSON.stringify({ keywords: ['dì Hoa', 'Hoa'], recipient: 'Dì Hoa', greeting: 'Chúc dì Hoa bình an!', title: 'Thương dì' }) })).json();
  assert.ok(custom.data.id);
  const personal = await (await post('/api/greetings/generate', { name: 'DI HOA', audienceType: 'family' })).json();
  assert.equal(personal.data.greeting, 'Chúc dì Hoa bình an!');
  const unrelated = await (await post('/api/greetings/generate', { name: 'Hoàng', audienceType: 'family' })).json();
  assert.notEqual(unrelated.data.greeting, 'Chúc dì Hoa bình an!');
  const deletePath = `/api/admin/feedback/${payload.requestId}`;
  assert.equal((await fetch(base + deletePath, { method: 'DELETE' })).status, 401);
  assert.equal((await fetch(base + deletePath, { method: 'DELETE', headers: authHeaders })).status, 200);
  assert.equal((await fetch(base + deletePath, { method: 'DELETE', headers: authHeaders })).status, 200);
  const afterDelete = await (await fetch(base + '/api/feedback?name=ngoc')).json();
  assert.equal(afterDelete.data.total, 0);
  const adminAfterDelete = await (await fetch(base + '/api/admin/feedback', { headers: authHeaders })).json();
  assert.equal(adminAfterDelete.data.total, 1);
  const overviewAfterDelete = await (await fetch(base + '/api/admin/overview', { headers: authHeaders })).json();
  assert.equal(overviewAfterDelete.data.feedbackCount, 1);
  assert.equal((await post('/api/admin/blocked-ips', { ip: 'not-an-ip' })).status, 401);
  assert.equal((await fetch(base + '/api/admin/blocked-ips', { headers: authHeaders })).status, 200);
  assert.equal((await fetch(base + '/api/admin/blocked-ips', { method: 'POST', headers: { ...authHeaders, 'Content-Type': 'application/json' }, body: JSON.stringify({ ip: 'not-an-ip' }) })).status, 400);
  const blocked = await fetch(base + '/api/admin/blocked-ips', { method: 'POST', headers: { ...authHeaders, 'Content-Type': 'application/json' }, body: JSON.stringify({ ip: '127.0.0.1' }) });
  assert.equal(blocked.status, 201);
  assert.equal((await fetch(base + '/api/access')).status, 403);
  assert.equal((await post('/api/visits', { sessionId: 'blocked-session', page: '/' })).status, 403);
  const blockedList = await (await fetch(base + '/api/admin/blocked-ips', { headers: authHeaders })).json();
  assert.equal(blockedList.data.items[0].ip, '127.0.0.1');
  assert.equal((await fetch(base + '/api/admin/overview', { headers: authHeaders })).status, 200);
  assert.equal((await fetch(`${base}/api/admin/blocked-ips/127.0.0.1`, { method: 'DELETE', headers: authHeaders })).status, 200);
  assert.equal((await fetch(base + '/api/access')).status, 200);
  assert.equal((await post('/api/visits', { sessionId: 'unblocked-session', page: '/' })).status, 200);
  const { createJsonStore } = require('../services/jsonStore');
  assert.equal((await createJsonStore(dir).read('feedback', [])).length, 2);
});
